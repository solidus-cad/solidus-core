// Topological naming: each face receives a stable name, derived from its origin; edges and vertices
// are named by the faces they separate. Design: core/NAMING.md.
#pragma once

#include <TopTools_ShapeMapHasher.hxx>
#include <TopoDS_Shape.hxx>

#include <functional>
#include <optional>
#include <string>
#include <string_view>
#include <unordered_map>
#include <vector>

class BRepTools_History;

namespace cad {

/// Face names of a body. A face may carry aliases: the names of the faces merged into it.
class TopoNames {
public:
  struct Entry {
    std::string name;
    std::vector<std::string> aliases;
  };

  void set(const TopoDS_Shape& face, std::string name);
  void addAlias(const TopoDS_Shape& face, std::string alias);
  /// Explicit name of a free edge (surface boundary), through a virtual end face:
  /// "e(sx/side(l1)|sx/start)". It replaces "e(F|~)" as long as the edge stays free, and follows the history (Modified).
  void setEdge(const TopoDS_Shape& edge, std::string name);
  /// Explicit names of the free edges (setEdge).
  const std::unordered_map<TopoDS_Shape, std::string, TopTools_ShapeMapHasher, TopTools_ShapeMapHasher>& explicitEdges() const { return edges_; }
  /// Edge name formed from the faces it separates: "e(A|B)", faces sorted and deduplicated.
  static std::string edgeName(std::vector<std::string> faces);
  /// Name of the face, or nullptr if it is not named.
  const std::string* face(const TopoDS_Shape& face) const;
  size_t size() const { return faces_.size(); }

  /// Face names of `shape`, in TopExp::MapShapes order (= mesh identifiers).
  std::vector<std::string> faceNames(const TopoDS_Shape& shape) const;
  /// Edge names of `shape`, in TopExp::MapShapes order: "e(A|B)", A and B being the adjacent faces;
  /// a free edge (surface boundary, a single face): its explicit name, otherwise "e(A|~)".
  std::vector<std::string> edgeNames(const TopoDS_Shape& shape) const;
  /// Free edges of `shape` (surface boundaries: a single face, excluding seams), in TopExp::MapShapes order.
  static std::vector<bool> freeEdges(const TopoDS_Shape& shape);
  /// Vertex names: "v(A|B|C)".
  std::vector<std::string> vertexNames(const TopoDS_Shape& shape) const;

  /// Resolves a name (of a face, edge or vertex) to a sub-shape of `shape`. Face aliases are accepted.
  std::optional<TopoDS_Shape> find(const TopoDS_Shape& shape, std::string_view name) const;

  /// Input body of an operation: its shape and names.
  struct Input {
    const TopoDS_Shape* shape;
    const TopoNames* names;
  };
  /// Namer of generated faces (from an edge, a vertex or an input face), from the origin name.
  using GeneratedNamer = std::function<std::string(const std::string& originName)>;

  /// Face names of `result` after an operation, derived from its history:
  ///  - a kept or modified face keeps the name of its origin face;
  ///  - a face resulting from several faces (merge) takes the smallest name, the others become aliases;
  ///  - a face generated by an edge or a vertex is named by `generated`;
  ///  - a face split into several pieces: suffix "#k", sorted geometrically.
  static TopoNames derive(const TopoDS_Shape& result, const std::vector<Input>& inputs, const BRepTools_History& history,
                          const GeneratedNamer& generated);

private:
  std::unordered_map<TopoDS_Shape, Entry, TopTools_ShapeMapHasher, TopTools_ShapeMapHasher> faces_;
  std::unordered_map<TopoDS_Shape, std::string, TopTools_ShapeMapHasher, TopTools_ShapeMapHasher> edges_;
};

}  // namespace cad
