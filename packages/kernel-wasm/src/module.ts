import type { ContinuitySample, FlatPattern, Interference, ProjectedView, SceneView } from "@solidus-cad/sdk";

/**
 * Interface of the kernel.js module (Embind, bindings/wasm/kernel_bindings.cpp), produced by tools/build-kernel.sh.
 * The buffers returned by `mesh()` and `exportShape()` are views of the WASM memory: copy them immediately.
 */
export interface MeshViews {
  positions: Float32Array;
  normals: Float32Array;
  indices: Uint32Array;
  faceGroups: Int32Array;
  edges: Float32Array;
  edgeGroups: Int32Array;
}

/** Occurrence of a document already recomputed in the kernel, placed by a 4×4 matrix (column-major). */
export interface NativePlaced {
  key: string;
  docId: string;
  matrix: number[];
  cut?: boolean;
}

export interface NativeKernel {
  /**
   * Prepared document (JSON, see prepare.ts) → result (JSON). `resolve(featureId, payload)` completes the deferred
   * functions (JSON → JSON); it must not throw.
   */
  recompute(input: string, resolve?: (featureId: string, payload: string) => string): string;
  mesh(): MeshViews | null;
  /** Fine mesh of the body of document `docId` (deflection in mm; ≤ 0: default), for CAM: views to copy immediately. */
  camMesh(docId: string, deflection: number): MeshViews | null;
  /** Last body of document `docId` (null: last recomputed document). */
  exportShape(format: string, docId: string | null): Uint8Array;
  /** Occurrences of already recomputed documents, exported into a single file. */
  exportPlaced(format: string, parts: NativePlaced[]): Uint8Array;
  /** Mesh identifier of a face or edge of the document designated by its topological name (-1 if not found). */
  resolveName(name: string, docId: string): number;
  /** Flat pattern of the sheet metal of the document (last recompute); throws if the part is not sheet metal. */
  flatPattern(docId: string): FlatPattern;
  /** Memory of the module: bytes allocated by malloc, size of the WASM heap (it only grows). */
  memory(): { used: number; heap: number };
  /** Curvature at each vertex of the display mesh of the document (gaussian, mean, min, max). */
  surfaceAnalysis(docId: string, kind: string): Float32Array;
  /** Continuity along an edge (topological name) of the document. */
  continuity(docId: string, edge: string): ContinuitySample[];
  /** Interferences between occurrences of already recomputed documents. */
  interferences(parts: NativePlaced[]): Interference[];
  /** Views of a scene of already recomputed documents. */
  projectScene(items: NativePlaced[], views: SceneView[]): ProjectedView[];
  /** Frees the cache of a closed document. */
  forget(docId: string): void;
  /** Frees the least recent documents beyond the limit (between two requests). */
  trim(): void;
  delete(): void;
}

export interface KernelModule {
  Kernel: new () => NativeKernel;
}

export type KernelFactory = (options?: { locateFile?: (path: string) => string }) => Promise<KernelModule>;

/** Loads kernel.js (dist/). `wasmUrl`: URL of kernel.wasm (browser); by default, next to kernel.js. */
export async function loadKernelModule(wasmUrl?: string): Promise<KernelModule> {
  // @ts-ignore -- generated by tools/build-kernel.sh (packages/kernel-wasm/dist).
  const mod = (await import("../dist/kernel.js")) as { default: KernelFactory };
  return mod.default(wasmUrl ? { locateFile: () => wasmUrl } : undefined);
}
