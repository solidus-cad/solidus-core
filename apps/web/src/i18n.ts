export type UiLang = (typeof UI_LANGS)[number]["id"];

const isUiLang = (v: unknown): v is UiLang => UI_LANGS.some((l) => l.id === v);

const initial: UiLang = (() => {
  try {
    const saved = localStorage.getItem("cad.lang");
    if (isUiLang(saved)) return saved;
  } catch {
    /* storage unavailable */
  }
  // User choice > language set by cad.config.toml (desktop) > system language.
  const configured = runtimeConfig.ui?.language;
  if (isUiLang(configured)) return configured;
  const full = navigator.language;
  const sys = /^zh-(TW|HK|MO|Hant)/i.test(full) ? "zh-TW" : full.slice(0, 2).toLowerCase();
  return isUiLang(sys) ? sys : "en";
})();

const [uiLang, setLangSignal] = createSignal<UiLang>(initial);
export { uiLang };

/** Content language derived from the interface language: French or English. */
export const lang = (): Lang => (uiLang() === "fr" ? "fr" : "en");

type PackLoaders = Record<string, () => Promise<Record<string, string>>>;

/** Translation source: one JSON file per language (name `<language>.json`), loaded on demand. */
const sources: { prefix: string; loaders: PackLoaders }[] = [];
const [pack, setPack] = createSignal<Record<string, string>>({});

/** Registers a JSON file per language; the keys of the file are prefixed with `prefix` (empty for the kernel, which `t()` reads). */
function registerLocales(loaders: PackLoaders, prefix = ""): void {
  sources.push({ prefix, loaders });
  loadPack(uiLang());
}

/**
 * Dictionary specific to a module (workspace, plugin): its `fr`/`en` texts stay there, its translations
 * are in one JSON file per language (`import.meta.glob("./locales/*.json", { import: "default" })`, keys of the dictionary).
 * `ns` isolates the module from the others and from the kernel. Returns the translation function of the module.
 */
export function defineTexts<D extends Record<string, I18nText>>(ns: string, dict: D, loaders: PackLoaders): (key: keyof D & string) => string {
  registerLocales(loaders, `${ns}:`);
  return (key) => packText(`${ns}:${key}`) ?? dict[key]![lang()];
}

/** Translated text of a language loaded on demand, or `undefined` (falls back to fr/en). */
export const packText = (key: string): string | undefined => pack()[key];

let packSeq = 0;
function loadPack(l: UiLang): void {
  const seq = ++packSeq;
  const loads = sources.flatMap(({ prefix, loaders }) =>
    Object.entries(loaders)
      .filter(([path]) => path.endsWith(`/${l}.json`))
      .map(([, load]) => load().then((p) => Object.entries(p).map(([k, v]): [string, string] => [prefix + k, v]))),
  );
  void Promise.all(loads).then(
    (all) => seq === packSeq && setPack(Object.fromEntries(all.flat())),
    () => seq === packSeq && setPack({}),
  );
}

function applyLang(l: UiLang): void {
  // Without DOM (unit tests under Node, which import this module through the shortcuts or the modules): texts only.
  if (typeof document !== "undefined") {
    document.documentElement.lang = l;
    document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
  }
  loadPack(l);
}
registerLocales(import.meta.glob<Record<string, string>>("./locales/*.json", { import: "default" }));
// Declarative texts ({ fr, en } of the built-in workbenches, datum panel, gears): translations keyed by the English text.
registerLocales(import.meta.glob<Record<string, string>>("./locales/tx/*.json", { import: "default" }), "en:");
applyLang(initial);

export function setLang(l: UiLang): void {
  setLangSignal(l);
  applyLang(l);
  try {
    localStorage.setItem("cad.lang", l);
  } catch {
    /* storage unavailable */
  }
}

/** Translates a text provided by a workspace or a plugin: its own language, else locales/tx (keyed by the English text), else fr/en. */
export const tx = (text: I18nText): string => text[uiLang()] ?? packText(`en:${text.en}`) ?? text[lang()];

